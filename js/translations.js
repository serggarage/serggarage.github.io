// 2. Aggressive Global Execution Engine
window.executeLanguageSwitch = function(lang) {
    console.log("Forcing layout interface swap to:", lang);
    
    // Hunt down every single tag matching your data key
    const elements = document.querySelectorAll('[data-lang-key]');
    
    elements.forEach(element => {
        const key = element.getAttribute('data-lang-key');
        if (window.translations[lang] && window.translations[lang][key]) {
            // Force write to textContent, innerHTML, AND innerText to break any template mirror layers
            element.innerHTML = window.translations[lang][key];
            element.textContent = window.translations[lang][key];
            element.innerText = window.translations[lang][key];
        }
    });

    // Update the visual look of your buttons
    document.querySelectorAll('.lang-btn').forEach(btn => btn.classList.remove('active'));
    const activeBtn = document.querySelector(`[data-lang-target="${lang}"]`) || document.querySelector(`.lang-btn[onclick*="${lang}"]`);
    if (activeBtn) activeBtn.classList.add('active');

    localStorage.setItem('preferredLanguage', lang);
};

// 3. Intercept ghost inline clicks
window.switchLanguage = function(lang) {
    window.executeLanguageSwitch(lang);
};

// 4. Force Active Click Binding to override template listeners
window.addEventListener("load", () => {
    const bindButtons = () => {
        const buttons = document.querySelectorAll('[data-lang-target], .lang-btn');
        buttons.forEach(button => {
            // Remove old listeners to clear memory loops
            button.replaceWith(button.cloneNode(true));
        });

        // Re-fetch clean buttons and apply pristine click rules
        const cleanButtons = document.querySelectorAll('[data-lang-target], .lang-btn');
        cleanButtons.forEach(button => {
            button.addEventListener('click', (e) => {
                // Read language from inline attribute or text content as a safety net
                const selectedLang = e.currentTarget.getAttribute('data-lang-target') || 
                                     e.currentTarget.getAttribute('onclick')?.match(/'([^']+)'/)?.[1] || 
                                     e.currentTarget.textContent.trim().toLowerCase();
                window.executeLanguageSwitch(selectedLang);
            });
        });

        // Run the initial preference render
        const savedLang = localStorage.getItem('preferredLanguage') || 'en';
        window.executeLanguageSwitch(savedLang);
    };

    // Run once at load, and run again at 1 second to catch sluggish preloaders
    bindButtons();
    setTimeout(bindButtons, 1000);
});